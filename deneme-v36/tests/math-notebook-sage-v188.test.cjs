"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,"..");
const decor=fs.readFileSync(path.join(root,"assets/math-notebook-forest-v186.css"),"utf8");
const notebook=fs.readFileSync(path.join(root,"assets/math-notebook-v187.js"),"utf8");
const quiz=fs.readFileSync(path.join(root,"forest-v70-quiz.html"),"utf8");
const forest=fs.readFileSync(path.join(root,"forest-v113-full.html"),"utf8");
const bank=JSON.parse(fs.readFileSync(path.join(root,"forest-questions-v147.json"),"utf8"));
new vm.Script(notebook,{filename:"math-notebook-v187.js"});
assert(decor.includes("background:#f2f8ef!important")&&decor.includes("background-color:#f2f8ef!important"),"Notebook and margins should be pale sage green");
assert(decor.includes("padding:1px!important"),"Remove dark green side gutters");
assert(decor.includes("background-repeat:repeat-y!important"),"Ivy watermark should scroll with paper");
assert(decor.includes("opacity:.14!important"),"Ivy must be translucent");
assert(decor.includes("pointer-events:none!important"),"Ivy cannot block handwriting");
assert(decor.includes(".mn-paper[data-paper=grid]")&&decor.includes(".mn-paper[data-paper=lined]")&&decor.includes(".mn-paper[data-paper=plain]"),"All paper types remain available");
assert(notebook.includes("workspace.clientWidth-4"),"Paper should reach frame edges");
assert(notebook.includes('note.zoom'),"Keep working zoom rather than forcing it to 100%");
assert(notebook.includes("liveSegments=new Map()"),"Keep iPhone-safe chunked canvas rendering");
assert(notebook.includes('note.tool==="hand"||pointer!==null'),"Hand and pen modes must still be distinct");
assert(notebook.includes("localStorage.setItem(key,JSON.stringify(note))"),"Writing must be stored");
assert(quiz.includes("math-notebook-forest-v186.css?v=188"),"New decoration must bypass iPhone cache");
assert(quiz.includes("math-notebook-v187.js?v=192"),"New paper fit must bypass iPhone cache");
assert(forest.includes("forest-v70-quiz.html?v=192"),"Live forest should load updated worksheet");
assert.equal(bank.questions.length,630,"Original question bank must remain unchanged");
console.log("PASS v188: edge-to-edge sage paper, subtle repeating ivy, readable grids, durable writing, unchanged 630 questions.");
