"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,"..");
const js=fs.readFileSync(path.join(root,"assets/math-notebook-v187.js"),"utf8");
const css=fs.readFileSync(path.join(root,"assets/math-notebook-fix-v192.css"),"utf8");
const svg=fs.readFileSync(path.join(root,"assets/forest-ivy-v192.svg"),"utf8");
const quiz=fs.readFileSync(path.join(root,"forest-v70-quiz.html"),"utf8");
const forest=fs.readFileSync(path.join(root,"forest-v113-full.html"),"utf8");
const bank=JSON.parse(fs.readFileSync(path.join(root,"forest-questions-v147.json"),"utf8"));
new vm.Script(js,{filename:"math-notebook-v187.js"});
const sandbox={window:{},Number,Math,Map,encodeURIComponent};
vm.runInNewContext(js,sandbox);
const api=sandbox.window.MTKMathNotebookTest;
assert(api&&typeof api.gridStepPx==="function","Expose stable grid sizing for regression tests");
assert.equal(api.gridStepPx(1),26,"A normal square should be 26 CSS pixels in both orientations");
assert.equal(api.gridStepPx(.9),23,"90% zoom should use 23 CSS pixels, not scale with screen width");
assert.equal(api.gridStepPx(2),42,"Prevent excessively large squares at maximum zoom");
assert.equal(api.gridStepPx(.7),22,"Minimum zoom must keep squares legible");
assert(!js.includes("84*scale"),"Remove landscape-width-dependent oversized grid");
assert(js.includes('id="mn-erase"')&&js.includes('<svg viewBox="0 0 24 24" aria-hidden="true">'),"Restore clear eraser pictogram");
assert(css.includes("#eef5ea")&&css.includes("background:var(--mn-sage)!important"),"Restore sage-green paper and side areas");
assert(css.includes('.mn-paper[data-paper="grid"]')&&css.includes('.mn-paper[data-paper="lined"]')&&css.includes('.mn-paper[data-paper="plain"]'),"All three backgrounds must be preserved");
assert(css.includes('background-size:var(--mn-grid-step,26px) var(--mn-grid-step,26px)'),"Grid and paper scale must be independent");
assert(css.includes('url("./forest-ivy-v192.svg")'),"Use the sharp SVG ivy instead of upscaled low-resolution WebP");
assert(!css.includes("erdem-ivy-paper-v191.webp"),"No low-resolution bitmap should be used by active styling");
assert(svg.startsWith("<svg")&&svg.includes("</svg>")&&svg.includes("<path"),"Botanical image must be a real vector");
assert(css.includes("background-repeat:repeat-y!important"),"Ivy must remain continuous down the endless page");
assert(css.includes("pointer-events:none!important")&&css.includes("z-index:2!important"),"Decor must not cover handwriting");
assert(quiz.includes('math-notebook-fix-v192.css?v=192')&&quiz.includes('math-notebook-v187.js?v=192'),"Latest assets must load after legacy CSS");
assert(quiz.indexOf("math-notebook-ui-v191.css")<quiz.indexOf("math-notebook-fix-v192.css"),"Last stylesheet must override old white paper");
assert(forest.includes('forest-v70-quiz.html?v=192'),"Host must load v192 on iPhone");
assert(forest.includes('#quizOverlay[data-notebook-open="1"]{padding:0!important;inset:0!important}'),"Landscape notebook should use the unused outer margins");
assert(css.includes("grid-template-rows:min-content min-content minmax(0,1fr)"),"Writing area must use remaining landscape height");
assert(js.includes('note.tool==="hand"||pointer!==null')&&js.includes('localStorage.setItem(key,JSON.stringify(note))'),"Keep hand lock and saved ink");
assert.equal(bank.questions.length,630,"Original question bank must remain unchanged");
console.log("PASS v192: SVG ivy, sage paper, eraser icon, 23–26px orientation-stable grid, larger landscape canvas, 630 original questions.");
