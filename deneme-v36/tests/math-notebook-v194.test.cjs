"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,"..");
const css=fs.readFileSync(path.join(root,"assets/math-notebook-retina-v194.css"),"utf8");
const source=fs.readFileSync(path.join(root,"assets/ivy-original-retina-v194.webp"));
const js=fs.readFileSync(path.join(root,"assets/math-notebook-v187.js"),"utf8");
const quiz=fs.readFileSync(path.join(root,"forest-v70-quiz.html"),"utf8");
const forest=fs.readFileSync(path.join(root,"forest-v113-full.html"),"utf8");
const bank=JSON.parse(fs.readFileSync(path.join(root,"forest-questions-v147.json"),"utf8"));
new vm.Script(js);
assert.equal(source.toString("ascii",0,4),"RIFF","The actual original ivy strip must be valid WebP");
assert.equal(source.toString("ascii",8,12),"WEBP");
assert.equal(source.toString("ascii",12,16),"VP8 ");
const width=source.readUInt16LE(26)&0x3fff;
const height=source.readUInt16LE(28)&0x3fff;
assert.equal(width,256,"Retain independent left/right source strips, 128px each");
assert.equal(height,1536,"Retain vertical pixels from user's full original paper");
assert.equal(width/2/40,3.2,"Retina 3x output must downsample, never pixelate from upscaling");
assert(css.includes('url("./ivy-original-retina-v194.webp")'),"Load the actual high-resolution ivy asset");
assert(css.includes("background-size:80px auto!important"),"Two 40px stripes must align with source halves");
assert(css.includes("background-position:left top!important"),"Left original border missing");
assert(css.includes("background-position:right top!important"),"Right original border missing");
assert(css.includes("image-rendering:auto!important")&&!css.includes("pixelated"),"Smooth image interpolation required");
assert(css.includes("background-repeat:repeat-y!important"),"Border must repeat down the scroll");
assert(css.includes("pointer-events:none!important"),"Ivy must not intercept touch writing");
assert(css.includes("mix-blend-mode:multiply!important"),"Leaf background must not overwrite sage paper");
assert(quiz.includes("math-notebook-retina-v194.css?v=194"),"Cache-bust the retina fix");
assert(quiz.indexOf("math-notebook-iphone-v193.css")<quiz.indexOf("math-notebook-retina-v194.css"),"Retina fix must load last");
assert(forest.includes("forest-v70-quiz.html?v=197"),"Active forest must open the new notebook");
assert(js.includes("gridStepPx(note.zoom)")&&js.includes("localStorage.setItem(key,JSON.stringify(note))"),"Keep stable squares and stored student ink");
assert.equal(bank.questions.length,630,"Keep the original question bank intact");
console.log("PASS v194: native original ivy at 3.2x source/Retina density, preserved paper and all 630 questions.");
