"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,"..");
const js=fs.readFileSync(path.join(root,"assets/math-notebook-v187.js"),"utf8");
const css=fs.readFileSync(path.join(root,"assets/math-notebook-v187.css"),"utf8");
const quiz=fs.readFileSync(path.join(root,"forest-v70-quiz.html"),"utf8");
const forest=fs.readFileSync(path.join(root,"forest-v113-full.html"),"utf8");
const bank=JSON.parse(fs.readFileSync(path.join(root,"forest-questions-v147.json"),"utf8"));
new vm.Script(js,{filename:"math-notebook-v187.js"});
assert(js.includes('const side=element("aside","mn-side-rail")'),"Create one shared responsive tool rail");
assert(js.includes('const nav=root.querySelector(".mn-toolbar")'),"Reuse the working toolbar inside the landscape rail");
assert(js.includes('root.insertBefore(side,root.querySelector(".mn-settings"))'),"Rail must precede tool settings and worksheet");
assert(css.includes(".mn-side-rail{display:contents!important}"),"Portrait UI must not change");
assert(css.includes("@media(orientation:landscape)"),"Landscape layout missing");
assert(css.includes("grid-template-columns:clamp(56px,7.7vw,77px) minmax(0,1fr)"),"Paper must use remaining horizontal space");
assert(css.includes("grid-template-rows:auto auto minmax(0,1fr)"),"Header + question must precede paper");
assert(css.includes("grid-column:1/-1!important;grid-row:2!important"),"Question must span full width");
assert(css.includes("grid-column:1!important;grid-row:3!important"),"Tools must occupy left rail");
assert(css.includes("grid-column:2!important;grid-row:3!important"),"Paper must be beside tools");
assert(css.includes(".mn-footer #mn-status:not([data-error=\"true\"]){display:none!important}"),"Status must not take paper height");
assert(css.includes(".mn-option-panel[hidden]{display:none!important}"),"Only active settings visible");
assert(css.includes("@media(orientation:landscape) and (max-height:380px)"),"Small landscape phones must fit");
assert(js.includes("liveSegments=new Map()")&&js.includes("localStorage.setItem(key,JSON.stringify(note))"),"Save and virtualize writing");
assert(js.includes('note.tool==="hand"||pointer!==null'),"Hand tool must not draw");
assert(quiz.includes("math-notebook-v187.css?v=189")&&quiz.includes("math-notebook-v187.js?v=192"),"Cache bust missing");
assert(forest.includes("forest-v70-quiz.html?v=192"),"Live forest route not updated");
assert.equal(bank.questions.length,630,"Original approved question bank must stay intact");
console.log("PASS v189: vertical landscape rail, wide paper under question, intact portrait and persistent notes.");
