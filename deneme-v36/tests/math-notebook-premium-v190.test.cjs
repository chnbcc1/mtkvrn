"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const base=path.resolve(__dirname,"..");
const css=fs.readFileSync(path.join(base,"assets/math-notebook-premium-v190.css"),"utf8");
const layout=fs.readFileSync(path.join(base,"assets/math-notebook-v187.css"),"utf8");
const js=fs.readFileSync(path.join(base,"assets/math-notebook-v187.js"),"utf8");
const quiz=fs.readFileSync(path.join(base,"forest-v70-quiz.html"),"utf8");
const forest=fs.readFileSync(path.join(base,"forest-v113-full.html"),"utf8");
const bank=JSON.parse(fs.readFileSync(path.join(base,"forest-questions-v147.json"),"utf8"));
new vm.Script(js);
assert(css.includes("background:#f2f8ef!important"),"The page stays pale sage green");
assert(css.includes("background-color:#f2f8ef!important"),"Premium frame must not hide sage paper");
assert(css.includes("padding:1px!important"),"Do not restore dark green gutters");
assert(css.includes("background-repeat:no-repeat,repeat-y!important"),"Corner filigree stays put while vines repeat down the page");
assert(css.includes("width:min(12%,56px)!important"),"Watermark stays at the paper margins");
assert(css.includes("opacity:.19!important")&&css.includes("opacity:.16!important"),"Vines are translucent");
assert(css.includes("pointer-events:none!important"),"Decor cannot intercept finger writing");
assert(css.includes("z-index:2!important"),"Writing remains above decoration");
assert.equal(css.split("data:image/svg+xml,").length-1,2,"Both corner filigree and vine should be vector graphics");
assert(layout.includes("grid-template-columns:clamp(56px,7.7vw,77px) minmax(0,1fr)"),"Keep the landscape left rail");
assert(js.includes("liveSegments=new Map()"),"Keep the virtualized long paper");
assert(js.includes("localStorage.setItem(key,JSON.stringify(note))"),"Preserve previously written ink");
assert(quiz.includes("math-notebook-premium-v190.css?v=190"),"Load the new premium paper on real questions");
assert(forest.includes("forest-v70-quiz.html?v=195"),"Invalidate the forest quiz cache");
assert.equal(bank.questions.length,630,"Keep the 630 approved original questions");
console.log("PASS v190: premium ornate sage paper, protected handwriting, landscape layout and 630 questions.");
