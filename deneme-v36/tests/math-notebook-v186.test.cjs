"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const root=path.resolve(__dirname,"..");
const js=fs.readFileSync(path.join(root,"assets/math-notebook-v186.js"),"utf8");
const base=fs.readFileSync(path.join(root,"assets/math-notebook-v186.css"),"utf8");
const vines=fs.readFileSync(path.join(root,"assets/math-notebook-forest-v186.css"),"utf8");
const quiz=fs.readFileSync(path.join(root,"forest-v70-quiz.html"),"utf8");
const forest=fs.readFileSync(path.join(root,"forest-v113-full.html"),"utf8");
const bank=JSON.parse(fs.readFileSync(path.join(root,"forest-questions-v147.json"),"utf8"));
new vm.Script(js,{filename:"math-notebook-v186.js"});
const sandbox={window:{},Math,Number,Map,encodeURIComponent};
vm.runInNewContext(js,sandbox);
const api=sandbox.window.MTKMathNotebook,helper=sandbox.window.MTKMathNotebookTest;
assert(api&&helper&&typeof api.attach==="function"&&typeof api.hide==="function");
assert.equal(helper.docWidth,1000);
assert.equal(helper.docHeight,1414);
assert.notEqual(helper.keyFor("F02-O-07"),helper.keyFor("F02-O-08"),"Notes must belong to distinct questions");
const stroke={tool:"pen",color:"#173b36",size:5,points:[[150,200],[160,220],[173,239]]};
const saved={version:1,pages:[{strokes:[stroke]},{strokes:[]}],page:0,paper:"grid",zoom:1.4,penSize:7,eraserSize:29,color:"#173b36"};
const restored=helper.normalize(saved);
assert.equal(restored.pages.length,2);
assert.equal(restored.pages[0].strokes.length,1);
assert.equal(restored.pages[0].strokes[0].points[2][1],239);
assert.equal(restored.zoom,1.4);
assert.equal(restored.paper,"grid");
assert.equal(helper.normalize(null).pages.length,1);
assert.equal(helper.normalize({...saved,zoom:99}).zoom,2);
assert.equal(helper.normalize({...saved,page:50}).page,1);
const point=helper.logicalPoint({clientX:125,clientY:250},{left:25,top:50,width:200,height:400});
assert.equal(point[0],500);
assert.equal(point[1],707);
assert(js.includes('canvas.addEventListener("pointerdown",pointerDown)'),"Pencil must draw by touch and pointer");
assert(js.includes('canvas.addEventListener("pointercancel",pointerEnd)'),"Interrupted touch strokes must persist");
assert(js.includes('e.getCoalescedEvents()'),"Smooth touch samples required");
assert(js.includes('localStorage.setItem(key,JSON.stringify(note))'),"Each question must be stored on device");
assert(js.includes('globalCompositeOperation=stroke.tool==="erase"?"destination-out":"source-over"'),"Eraser must remove ink");
assert(js.includes('redone=new Map()')&&js.includes('function undo()')&&js.includes('function redo()'),"Undo/redo missing");
assert(js.includes('note.pages.push({strokes:[]})')&&js.includes('function setPage('),"Multi-page notebook missing");
assert(js.includes('global.confirm("Bu sayfadaki bütün işlemler silinecek.'),"Clear must be confirmed");
assert(js.includes('question={id,text,scene:String(info.scene||"")}'),"Forest theme must be contextual");
assert(js.includes('note.pages.length>=250'),"Storage-aware page limit missing");
assert(base.includes('touch-action:none!important')&&base.includes('.mn-root[hidden]{display:none!important}'),"Touch-first modal missing");
assert(base.includes('overflow:auto!important')&&base.includes('@media(orientation:landscape)'),"Notebook must support zoom and landscape");
assert(vines.includes('.mn-root.mn-forest .mn-paper::before')&&vines.includes('pointer-events:none!important'),"Non-obstructing forest vines missing");
assert(vines.includes('z-index:2!important')&&vines.includes('.mn-segment'),"Handwriting must paint above forest decoration");
assert(quiz.includes('math-notebook-v187.js?v=196')&&quiz.includes('math-notebook-v187.css?v=189')&&quiz.includes('math-notebook-forest-v186.css?v=188'),"Notebook resources not loaded");
assert(quiz.includes('window.MTKMathNotebook?.attach({questionId:q.id,questionText:s.prompt,scene:"forest"})'),"Actual staged question must connect to its own notebook");
assert(quiz.includes('window.MTKMathNotebook?.hide();window.MTKApprovedQuizV145?.reset()'),"Notebook must hide in home menu");
assert(/forest-v70-quiz\.html\?v=\d+/.test(forest),"Forest chapter must load the updated quiz");
assert.equal(bank.questions.length,630);
for(const q of bank.questions)assert(q.id&&q.prompt&&q.correctAnswer,"Missing approved question data: "+q.id);
console.log("PASS v186: forest ivy, touch pen/eraser, undo/redo, multi-page note persistence, per-question restore and unchanged 630 questions.");
